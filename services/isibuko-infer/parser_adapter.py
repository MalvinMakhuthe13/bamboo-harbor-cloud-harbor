"""Replaceable human-parser boundary for still-image try-on.

The diffusion network takes a person image, a garment image, two pose
images, and a category id. It does not take a segmentation map.
FASHN's published pipeline still builds those images with FashnHumanParser,
whose weights inherit the NVIDIA Source Code License for SegFormer
(non-commercial: research or evaluation only).

This module does not import that package and does not download it.
A provider may be attached only when it is commercially cleared and emits
the 18 public class ids. None is attached.
"""

from __future__ import annotations

from typing import Any

# Public class ids from fashn-human-parser labels.py, read 11 November 2026.
# Recording the names is not a copy of the model.
FASHN_LABEL_IDS: dict[str, int] = {
    "background": 0,
    "face": 1,
    "hair": 2,
    "top": 3,
    "dress": 4,
    "skirt": 5,
    "pants": 6,
    "belt": 7,
    "bag": 8,
    "hat": 9,
    "scarf": 10,
    "glasses": 11,
    "arms": 12,
    "hands": 13,
    "legs": 14,
    "feet": 15,
    "torso": 16,
    "jewelry": 17,
}

# What the preprocessor keeps for each try-on category, from the same file.
CATEGORY_GARMENT_LABELS: dict[str, tuple[str, ...]] = {
    "tops": ("top", "dress", "scarf"),
    "bottoms": ("skirt", "pants", "belt"),
    "one-pieces": ("top", "dress", "scarf", "skirt", "pants", "belt"),
}

# MediaPipe selfie multiclass, already used by the on-device mirror.
# It cannot say top from pants, or arms from torso.
MEDIAPIPE_SELFIE_LABELS: tuple[str, ...] = (
    "background",
    "hair",
    "body-skin",
    "face-skin",
    "clothes",
    "others",
)


class ParserLicenceError(Exception):
    pass


_CLEARED: dict[str, dict[str, Any]] = {}


def register_parser(spec: dict[str, Any]) -> None:
    """Attach a parser that is allowed to feed a masked try-on."""
    parser_id = str(spec.get("id", "")).strip()
    if parser_id == "fashn-human-parser":
        raise ParserLicenceError("The NVIDIA SegFormer parser cannot be registered for this product.")
    if spec.get("commercialCleared") is not True:
        raise ParserLicenceError("A parser without commercial clearance cannot be registered.")
    labels = spec.get("labelIds")
    if not isinstance(labels, dict) or set(labels.values()) != set(FASHN_LABEL_IDS.values()):
        raise ParserLicenceError("A replacement parser must emit all 18 FASHN class ids, not a binary mask.")
    _CLEARED[parser_id] = {"id": parser_id, "commercialCleared": True}


def cleared_parsers() -> list[str]:
    return sorted(_CLEARED)


def plan_parser(
    parser_id: str,
    segmentation_free: bool,
    garment_photo_type: str,
) -> dict[str, Any]:
    """Decide whether this request can run without the NVIDIA parser.

    The published pipeline discards the label map when segmentation_free is
    true and the garment is a flat-lay. Every other combination uses the map.
    That was read from pipeline.py on 11 November 2026. It was not measured
    by generating an image.
    """
    base: dict[str, Any] = {
        "parserId": parser_id,
        "segmentationFree": segmentation_free,
        "garmentPhotoType": garment_photo_type,
        "usesNvidiaParser": False,
        "run": False,
    }
    if parser_id == "fashn-human-parser":
        base["code"] = "PARSER_NON_COMMERCIAL"
        base["usesNvidiaParser"] = True
        base["message"] = (
            "FASHN Human Parser inherits the NVIDIA Source Code License for SegFormer, "
            "which limits the work to research or evaluation. It is not used."
        )
        return base
    if parser_id == "mediapipe-selfie":
        base["code"] = "INSUFFICIENT_LABELS"
        base["message"] = (
            "MediaPipe selfie segmentation has six classes and no garment type. "
            "It cannot fill the 18-class map the masked route requires."
        )
        return base
    if parser_id == "sam2":
        base["code"] = "INSUFFICIENT_LABELS"
        base["message"] = (
            "SAM 2 can propose a mask from a prompt. It does not emit top, dress, pants, "
            "arms, or torso ids. It is not a drop-in parser. Its weight licence was not re-opened."
        )
        return base
    if parser_id in _CLEARED and not segmentation_free:
        base["code"] = "PARSER_READY"
        base["run"] = True
        base["message"] = "A cleared label-map parser is attached. No image has been generated by this status."
        return base
    if parser_id not in {"", "none"} and parser_id not in _CLEARED:
        base["code"] = "PARSER_NOT_REGISTERED"
        base["message"] = "That parser is not registered. No image was generated."
        return base
    if segmentation_free and garment_photo_type == "flat-lay" and parser_id == "none":
        base["code"] = "PARSER_SKIPPED"
        base["run"] = True
        base["message"] = (
            "Flat-lay garment and segmentation-free person image do not consume a label map. "
            "The NVIDIA parser is not called. This is not a generated image."
        )
        return base
    base["code"] = "PARSER_REQUIRED"
    base["message"] = (
        "A model-photo garment or a masked person image needs a commercially cleared 18-class parser. "
        "None is registered. The NVIDIA parser is not an acceptable substitute."
    )
    return base
